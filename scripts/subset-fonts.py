# Screen font subset: only the characters the app's own text uses (src/*.js, src/*.css, index.html, manifest) plus ASCII.
# The official NanumSquare Neo files stay untouched as the fallback face (any character outside the subset loads them)
# and as the certificate download's embedded font. NanumSquareNeo is a Reserved Font Name under the OFL, so the
# subset files carry their own internal name; the CSS alias stays "NanumSquareNeo" so every font stack keeps working.
# Run after changing on-screen text:
#   PYTHONPATH="/Volumes/T7 Shield/DevCaches/pydeps-fonttools" python3 scripts/subset-fonts.py
import glob, os, re
from fontTools import subset
from fontTools.ttLib import TTFont

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
START, END = '/* font-subset:start */', '/* font-subset:end */'

chars = {chr(c) for c in range(0x20, 0x7F)}
for path in sorted(glob.glob('src/*.js') + glob.glob('src/*.css') + ['index.html', 'manifest.webmanifest']):
    if os.path.basename(path).startswith('._'):
        continue
    text = open(path, encoding='utf-8').read()
    if path == 'src/styles.css' and START in text:
        text = text[:text.index(START)] + text[text.index(END):]
    chars |= {c for c in text if ord(c) >= 0x20}
codes = sorted(ord(c) for c in chars)

def ranges(values):
    out, start, prev = [], values[0], values[0]
    for v in values[1:] + [None]:
        if v is not None and v == prev + 1:
            prev = v
            continue
        out.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
        if v is not None:
            start = prev = v
    return out

faces = []
for weight, suffix in ((400, 'bRg'), (700, 'cBd')):
    src, dst = f'assets/fonts/NanumSquareNeoTTF-{suffix}.woff2', f'assets/fonts/climate-body-{weight}.woff2'
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    font = subset.load_font(src, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codes)
    subsetter.subset(font)
    # Modified Version under the OFL: give it a name outside the Reserved Font Names.
    family = 'Climate Lab Body'
    style = 'Bold' if weight == 700 else 'Regular'
    for record in font['name'].names:
        if record.nameID in (1, 16):
            record.string = family
        elif record.nameID == 4:
            record.string = f'{family} {style}'
        elif record.nameID == 6:
            record.string = f'ClimateLabBody-{style}'
        elif record.nameID == 3:
            record.string = f'Climate Lab Body {style}; subset of NanumSquare Neo (OFL)'
    subset.save_font(font, dst, options)
    covered = set(TTFont(dst).getBestCmap())
    missing = [c for c in codes if c not in covered]
    faces.append((weight, dst, [c for c in codes if c in covered]))
    print(f'{dst}: {os.path.getsize(dst)} bytes, {len(covered)} glyph codes, not in the original font: {"".join(chr(c) for c in missing) or "none"}')

block = [START, '/* Generated by scripts/subset-fonts.py. Official files first, limited to the characters they really have, so a symbol in neither'
         ' font (e.g. a check mark) goes straight to the system font instead of downloading the full file. The subset faces come last and win for the screen text. */']
for weight, suffix in ((400, 'bRg'), (700, 'cBd')):
    full = f'assets/fonts/NanumSquareNeoTTF-{suffix}.woff2'
    cmap = sorted(c for c in TTFont(full).getBestCmap() if c >= 0x20)
    block.append(f'@font-face {{ font-family: "NanumSquareNeo"; src: url("/{full}") format("woff2"); font-style: normal; font-weight: {weight}; font-display: swap; unicode-range: {", ".join(ranges(cmap))}; }}')
for weight, dst, covered in faces:
    block.append(f'@font-face {{ font-family: "NanumSquareNeo"; src: url("/{dst}") format("woff2"); font-style: normal; font-weight: {weight}; font-display: swap; unicode-range: {", ".join(ranges(covered))}; }}')
block.append(END)
css = open('src/styles.css', encoding='utf-8').read()
css = re.sub(r'@font-face \{ font-family: "NanumSquareNeo"; src: url\("/assets/fonts/NanumSquareNeoTTF-(bRg|cBd)\.woff2"\) format\("woff2"\); font-style: normal; font-weight: (400|700); font-display: swap; \}\n', '', css)
if START in css:
    css = css[:css.index(START)] + '\n'.join(block) + css[css.index(END) + len(END):]
else:
    anchor = css.index('\n') + 1  # after the license comment on the first line
    css = css[:anchor] + '\n'.join(block) + '\n' + css[anchor:]
open('src/styles.css', 'w', encoding='utf-8').write(css)
print(f'{len(codes)} characters, src/styles.css updated')
